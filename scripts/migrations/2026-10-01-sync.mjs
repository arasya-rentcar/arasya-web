/**
 * Owner decisions sync (idempotent: everything is set, nothing appended).
 *
 *  1. Company name is "PT Ayomi Raya Karsa" and the only official account is
 *     BCA 0954840782 a.n. PT Ayomi Raya Karsa (siteSettings.legalName and
 *     bankAccounts). Every other text in the dataset that still says
 *     "PT. Ayomi Raya" (fraud warning, FAQs, pages, posts, EN versions) is
 *     rewritten in place; nothing else in those fields is touched.
 *  2. Cancellation policy (ID + EN) matches what the booking system enforces:
 *     20% before the travel day, 50% until 10:00 WIB on the day, 100% after.
 *  3. All-in rate note (ID + EN): parking, overtime and out-of-town charges
 *     are confirmed separately when billed.
 *
 * Data: data/2026-10-01-sync.json (generated by scripts/content/apply.py).
 */
import { readFile } from 'node:fs/promises';

const OLD_NAME = /PT\.? Ayomi Raya(?! Karsa)/g;
const NEW_NAME = 'PT Ayomi Raya Karsa';

const toPath = (segs) =>
  segs.reduce((acc, s) => {
    if (typeof s === 'number') return `${acc}[${s}]`;
    if (typeof s === 'object') return `${acc}[_key=="${s._key}"]`;
    return acc ? `${acc}.${s}` : s;
  }, '');

/** Collect [path, newValue] for every string that still holds the old name. */
function findOld(node, segs, out) {
  if (typeof node === 'string') {
    if (OLD_NAME.test(node)) out.push([segs, node.replace(OLD_NAME, NEW_NAME)]);
    OLD_NAME.lastIndex = 0;
  } else if (Array.isArray(node)) {
    node.forEach((x, i) => findOld(x, [...segs, x && typeof x === 'object' && x._key ? { _key: x._key } : i], out));
  } else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) if (!k.startsWith('_')) findOld(v, [...segs, k], out);
  }
}

export default async function run(client) {
  const data = JSON.parse(await readFile(new URL('./data/2026-10-01-sync.json', import.meta.url), 'utf8'));

  // 1. Name and the single official account.
  const settings = await client.getDocument('siteSettings');
  const bank = { ...data.bank, _key: settings?.bankAccounts?.[0]?._key || data.bank._key };
  await client
    .patch('siteSettings')
    .setIfMissing({ en: {} })
    .set({
      legalName: data.legalName,
      bankAccounts: [bank],
      // 2. Cancellation policy, Indonesian and English.
      cancellationPolicy: data.policy,
      'en.cancellationPolicy': data.policyEn,
      // 3. All-in note.
      'rateNotes.allIn': data.rateNotesAllIn,
      'en.rateNotes.allIn': data.rateNotesAllInEn,
    })
    .commit({ visibility: 'sync' });
  console.log('siteSettings: legalName, bankAccounts, cancellationPolicy (id+en) and all-in notes set.');

  // Old legal name in any remaining text (set by path, so re-running is a no-op).
  const docs = await client.fetch('*[!(_id in path("_.**")) && !(_id in path("drafts.**"))]');
  const tx = client.transaction();
  let fields = 0;
  const touched = new Set();
  for (const doc of docs) {
    const found = [];
    findOld(doc, [], found);
    if (!found.length) continue;
    tx.patch(doc._id, (p) => p.set(Object.fromEntries(found.map(([segs, v]) => [toPath(segs), v]))));
    fields += found.length;
    touched.add(doc._id);
  }
  if (fields) await tx.commit({ visibility: 'sync' });
  console.log(`legal name: ${fields} text field(s) rewritten in ${touched.size} document(s).`);
}
