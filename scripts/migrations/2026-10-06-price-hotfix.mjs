/**
 * Owner price list of 6 Oct 2026 (idempotent: values are set, nothing
 * appended), until the site reads its prices from the API price list.
 *
 *  1. 12-hour in-town rates that differed from the owner's list:
 *     Zenix Q 1.400.000, Fortuner 1.600.000.
 *  2. All-in = the owner's Jakarta 12-hour all-in rate (the old figures were
 *     higher than any all-in rate on the list).
 *  3. Rate notes (ID + EN): the 12-hour rate is for Jabodetabek, driver meals
 *     Rp100.000/day, all-in is Jakarta for 12 hours, extra hours cost 10% of
 *     the full-day rate per hour.
 *  4. Bandung shows the fleet table as reference rates (Bandung has its own,
 *     higher all-in list).
 *
 * Data: data/2026-10-06-price-hotfix.json (generated by scripts/content/apply.py).
 */
import { readFile } from 'node:fs/promises';

export default async function run(client) {
  const data = JSON.parse(await readFile(new URL('./data/2026-10-06-price-hotfix.json', import.meta.url), 'utf8'));

  const tx = client.transaction();
  for (const [id, prices] of Object.entries(data.cars)) {
    // A null price means "on request"; whatever the Studio holds is left alone.
    const set = Object.fromEntries(Object.entries(prices).filter(([, v]) => v != null));
    tx.patch(id, (p) => p.set(set));
  }
  tx.patch('siteSettings', (p) =>
    p.setIfMissing({ en: {} }).set({
      'rateNotes.city': data.rateNotes.city,
      'rateNotes.allIn': data.rateNotes.allIn,
      'en.rateNotes.city': data.rateNotesEn.city,
      'en.rateNotes.allIn': data.rateNotesEn.allIn,
    }),
  );
  for (const [id, pricing] of Object.entries(data.cityPricing)) tx.patch(id, (p) => p.set({ pricing }));
  await tx.commit({ visibility: 'sync' });

  console.log(
    `prices set on ${Object.keys(data.cars).length} car(s); rate notes (id+en) set; ` +
      `pricing set on ${Object.keys(data.cityPricing).join(', ')}.`,
  );
}
