/**
 * Cancellation policy (ID + EN) per rental day: fees are a share of each day's
 * own price (20% / 50% / 100%), the 50% tier ends when the driver has arrived
 * at the pick-up address, and the closing text carries the extra-charges and
 * overpayment rules plus a worked example (owner decision 8 Oct 2026).
 *
 * Field by field: a field is replaced only when it still holds the previous
 * wording (data.previous). A Studio text that still has an old "hingga/sampai
 * pukul 10.00" phrase is first brought to the previous wording with the
 * 2026-10-08 rewrites, so this works whether or not that migration ran. A field
 * edited in the Studio is kept and reported. Title and intro are not touched.
 * Idempotent: after a run every field holds the new text, which is not the
 * previous text, so a second run changes nothing.
 *
 * Data: data/2026-10-09-policy-per-day.json (generated by scripts/content/apply.py).
 */
import { readFile } from 'node:fs/promises';

const FIELDS = ['when', 'fee', 'text'];

const rewrite = (text, rewrites) => rewrites.reduce((t, [from, to]) => t.split(from).join(to), text);

export default async function run(client) {
  const data = JSON.parse(await readFile(new URL('./data/2026-10-09-policy-per-day.json', import.meta.url), 'utf8'));
  const settings = await client.getDocument('siteSettings');
  if (!settings) throw new Error('siteSettings not found.');

  const current = { cancellationPolicy: settings.cancellationPolicy, 'en.cancellationPolicy': settings.en?.cancellationPolicy };
  const next = { cancellationPolicy: data.policy, 'en.cancellationPolicy': data.policyEn };
  const set = {};
  const kept = [];

  for (const field of Object.keys(next)) {
    const cur = current[field];
    if (!cur) {
      kept.push(`${field} (empty in Studio)`);
      continue;
    }
    const prev = data.previous[field];
    const want = next[field];
    const rw = data.rewrites[field];
    // Replace one string when it still holds the previous wording; log it otherwise unless it is already the new one.
    const swap = (path, live, before, after) => {
      if (live === after) return;
      if (typeof live === 'string' && rewrite(live, rw) === before) set[path] = after;
      else kept.push(path);
    };

    swap(`${field}.closing`, cur.closing, prev.closing, want.closing);
    const items = cur.items || [];
    if (items.length !== prev.items.length) {
      kept.push(`${field}.items (${items.length} items in Studio, expected ${prev.items.length})`);
      continue;
    }
    items.forEach((it, i) => {
      for (const f of FIELDS) swap(`${field}.items[_key=="${it._key}"].${f}`, it[f], prev.items[i][f], want.items[i][f]);
    });
  }

  if (Object.keys(set).length) {
    await client.patch('siteSettings').set(set).commit({ visibility: 'sync' });
  }
  const n = Object.keys(set).length;
  console.log(`cancellationPolicy (id+en): ${n} field(s) replaced${n ? ': ' + Object.keys(set).join(', ') : ' (already up to date)'}.`);
  if (kept.length) console.log(`Kept as in Studio (not the previous text, check by hand): ${kept.join('; ')}.`);
}
