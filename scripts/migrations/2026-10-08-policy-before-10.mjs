/**
 * Cancellation policy wording (ID + EN): the 50% tier ends *before* 10:00 WIB
 * on the travel day and the 100% tier starts *at* 10:00 WIB, so 10:00:00 itself
 * is already 100% (owner decision, same rule as computeCancellationPenalty).
 *
 * Only strings inside siteSettings.cancellationPolicy and
 * en.cancellationPolicy that still hold an old phrase ("sampai/hingga/s.d.
 * pukul 10.00" → "sebelum", "setelah pukul 10.00" → "mulai", "up to/until
 * 10 a.m." → "before", "after 10 a.m." → "from") are set, with just that phrase
 * replaced; the rest of the text, and any other Studio edit, is kept.
 * Idempotent: no new phrase contains an old one, so a second run finds
 * nothing and commits nothing.
 *
 * Data: data/2026-10-08-policy-before-10.json (generated by scripts/content/apply.py).
 */
import { readFile } from 'node:fs/promises';
import { isDeepStrictEqual } from 'node:util';

const toPath = (segs) =>
  segs.reduce((acc, s) => {
    if (typeof s === 'number') return `${acc}[${s}]`;
    if (typeof s === 'object') return `${acc}[_key=="${s._key}"]`;
    return acc ? `${acc}.${s}` : s;
  }, '');

const rewrite = (text, rewrites) => rewrites.reduce((t, [from, to]) => t.split(from).join(to), text);

/** Collect [path, newValue] for every string that still holds an old phrase. */
function findOld(node, segs, rewrites, out) {
  if (typeof node === 'string') {
    const next = rewrite(node, rewrites);
    if (next !== node) out.push([segs, next]);
  } else if (Array.isArray(node)) {
    node.forEach((x, i) => findOld(x, [...segs, x && typeof x === 'object' && x._key ? { _key: x._key } : i], rewrites, out));
  } else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) if (!k.startsWith('_')) findOld(v, [...segs, k], rewrites, out);
  }
}

/** Policy as stored, without _keys, for comparing with the seed. */
const plain = (cp) => cp && { ...cp, items: (cp.items || []).map(({ _key, ...it }) => it) };

export default async function run(client) {
  const data = JSON.parse(await readFile(new URL('./data/2026-10-08-policy-before-10.json', import.meta.url), 'utf8'));
  const settings = await client.getDocument('siteSettings');
  if (!settings) throw new Error('siteSettings not found.');

  const current = { cancellationPolicy: settings.cancellationPolicy, 'en.cancellationPolicy': settings.en?.cancellationPolicy };
  const found = [];
  for (const [field, rewrites] of Object.entries(data.rewrites)) {
    if (current[field]) findOld(current[field], field.split('.'), rewrites, found);
  }

  if (found.length) {
    await client
      .patch('siteSettings')
      .set(Object.fromEntries(found.map(([segs, v]) => [toPath(segs), v])))
      .commit({ visibility: 'sync' });
  }
  console.log(`cancellationPolicy (id+en): ${found.length} field(s) rewritten${found.length ? ': ' + found.map(([s]) => toPath(s)).join(', ') : ' (already up to date)'}.`);

  // Report (no change) whether Studio now says exactly what the seed says.
  const after = found.length ? await client.getDocument('siteSettings') : settings;
  for (const [label, live, seed] of [
    ['id', after.cancellationPolicy, data.policy],
    ['en', after.en?.cancellationPolicy, data.policyEn],
  ]) {
    console.log(`cancellationPolicy ${label}: ${isDeepStrictEqual(plain(live), plain(seed)) ? 'matches the seed' : 'differs from the seed (Studio edits kept, check by hand)'}.`);
  }
}
